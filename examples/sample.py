"""Demo module used to exercise the PR review bot end-to-end.

Harmless sample code — change anything here in a PR to trigger a review.
"""


def greet(name: str) -> str:
    """Return a friendly greeting."""
    return f"Hello, {name}!"


def add(a: int, b: int) -> int:
    """Add two numbers."""
    return a + b


def divide(a: int, b: int) -> float:
    """Divide the first number by the second."""
    return a / b
